export type Predicate = keyof typeof PREDICATES;
export const PREDICATE_NAMES = Object.keys(PREDICATES) as Predicate[];

export function isPredicate(value: string): value is Predicate {
  return Object.prototype.hasOwnProperty.call(PREDICATES, value);
}

export function predicateDefinition(predicate: Predicate): PredicateDefinition {
  return PREDICATES[predicate];
}

export const STACK_MEMBERSHIP_PREDICATES = PREDICATE_NAMES.filter((p) => PREDICATES[p].is_stack_membership);
export const RELATIONSHIP_PREDICATES = PREDICATE_NAMES.filter((p) => PREDICATES[p].value_kind === "ENTITY");
