import type { Cardinality, EntityType, EnumName, Unit, ValueKind } from "./enums.js";

// The predicate registry. Unknown predicates are rejected by validation.
// docs/ontology.md is the human-readable mirror of this file; keep them in sync.

export interface PredicateDefinition {
  /** Entity types that may be the subject of this claim. */
  subject_types: readonly EntityType[];
  /** Which value column the claim uses. ENTITY claims are relationships. */
  value_kind: ValueKind;
  /** For ENTITY claims: allowed entity types of the object. */
  object_types?: readonly EntityType[];
  /** For NUMBER claims: the canonical unit. Also the unit of `measure` on ENTITY claims. */
  unit?: Unit;
  /** For ENUM claims: which enum the value must belong to. */
  enum_name?: EnumName;
  /** ONE = at most one open APPROVED claim per subject (per stack layer if applicable). */
  cardinality: Cardinality;
  /** True for USES_PRODUCT / USES_TECHNOLOGY: the claim carries a stack_layer. */
  is_stack_membership: boolean;
  /** Whether the claim may (or must) carry a stack_layer. */
  stack_layer: "REQUIRED" | "FORBIDDEN";
  /** For ENTITY claims that also carry a number (SCORES_ON): value_number + unit are allowed. */
  measure?: boolean;
  /** Plain-words label used when rendering the claim as a sentence. */
  label: string;
  description: string;
}

